-- ============================================
-- 图书馆公告/活动管理系统 - 建表及示例数据
-- ============================================

CREATE TABLE IF NOT EXISTS announcement (
    id INT AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(200) NOT NULL COMMENT '公告/活动标题',
    content TEXT COMMENT '详细内容(HTML)',
    summary VARCHAR(500) COMMENT '摘要，用于列表展示',
    cover_image VARCHAR(500) COMMENT '封面图片路径',
    type VARCHAR(20) NOT NULL DEFAULT 'announcement' COMMENT '类型: announcement=公告, activity=活动',
    is_carousel TINYINT(1) DEFAULT 0 COMMENT '是否在轮播图展示 1=是 0=否',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='图书馆公告/活动表';

